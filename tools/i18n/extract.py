#!/usr/bin/env python3
"""Collects every translatable string into client/i18n/messages.pot and
merges it into each language's .po file (docs/localization.md).

Strings are English source text, marked in GDScript with tr("..."),
tr_n("one", "many", n), UI.t("...") or UI.tn("one", "many", n), or every
string on a line ending in `# tr` (constants translated where used); names and
texts from data/*.json (data_strings below) are added too. Translations
already in a .po are kept; new strings come in empty, gone ones are dropped.

    python3 tools/i18n/extract.py          # update the files
    python3 tools/i18n/extract.py --check  # fail if they're stale or a
                                           # string has no translation
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = ROOT / "client" / "scripts"
DATA = ROOT / "data"
OUT = ROOT / "client" / "i18n"
LANGUAGES = {
    "sr_Latn": {
        "name": "Serbian (Latin)",
        "plural": "nplurals=3; plural=(n%10==1 && n%100!=11 ? 0 : n%10>=2 && n%10<=4 && (n%100<10 || n%100>=20) ? 1 : 2);",
        "plurals": 3,
    },
}

STRING = r'"((?:\\.|[^"\\])*)"'
SINGLE = re.compile(r'(?:\btr|\bUI\.t)\(\s*' + STRING)
LINE_MARK = re.compile(r'#\s*tr\s*$')
ANY = re.compile(STRING)
PLURAL = re.compile(r'(?:\btr_n|\bUI\.tn)\(\s*' + STRING + r'\s*,\s*' + STRING)


def unescape(s):
    return s.replace('\\"', '"').replace("\\n", "\n").replace("\\t", "\t").replace("\\\\", "\\")


def escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def data_strings():
    """Player-facing texts in the game data: names, titles, descriptions."""
    keys = {"name", "title", "description", "faction", "signature", "story", "text", "label", "flavor", "body", "hint", "summary", "goal", "best", "weakness", "animal"}
    found = {}

    def walk(node, where):
        if isinstance(node, dict):
            for k, v in node.items():
                if k.startswith("_"):
                    continue
                if k in keys and isinstance(v, str) and v.strip():
                    found.setdefault(v, where)
                elif k in keys and isinstance(v, list) and all(isinstance(x, str) for x in v):
                    for x in v:
                        found.setdefault(x, where)
                else:
                    walk(v, where)
        elif isinstance(node, list):
            for item in node:
                walk(item, where)

    for path in sorted(DATA.glob("*.json")):
        walk(json.loads(path.read_text(encoding="utf-8")), f"data/{path.name}")
    return found


def collect():
    """{msgid: (plural or None, where)} in a stable order."""
    messages = {}
    for path in sorted(SCRIPTS.rglob("*.gd")):
        rel = path.relative_to(ROOT).as_posix()
        for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            for m in PLURAL.finditer(line):
                messages.setdefault(unescape(m.group(1)), (unescape(m.group(2)), f"{rel}:{lineno}"))
            for m in SINGLE.finditer(line):
                messages.setdefault(unescape(m.group(1)), (None, f"{rel}:{lineno}"))
            if LINE_MARK.search(line):
                for m in ANY.finditer(line.split("#")[0]):
                    messages.setdefault(unescape(m.group(1)), (None, f"{rel}:{lineno}"))
    for text, where in data_strings().items():
        messages.setdefault(text, (None, where))
    return messages


def parse_po(path):
    """{msgid: [msgstr, ...]} from a .po file."""
    if not path.exists():
        return {}
    entries, current, key = {}, {}, None
    for raw in path.read_text(encoding="utf-8").splitlines() + [""]:
        line = raw.strip()
        if not line or line.startswith("#"):
            if "msgid" in current:
                entries[current["msgid"]] = [current[k] for k in sorted(current) if k.startswith("msgstr")]
            if not line:
                current, key = {}, None
            continue
        m = re.match(r'^(msgid_plural|msgid|msgstr(?:\[\d\])?)\s+"(.*)"$', line)
        if m:
            key = m.group(1)
            current[key] = unescape(m.group(2))
        elif line.startswith('"') and key:
            current[key] += unescape(line[1:-1])
    entries.pop("", None)
    return entries


def render(messages, language=None, translations=None):
    head = ['msgid ""', 'msgstr ""', '"Content-Type: text/plain; charset=UTF-8\\n"']
    if language:
        lang = LANGUAGES[language]
        head += [f'"Language: {language}\\n"', f'"Plural-Forms: {lang["plural"]}\\n"']
    out = ["# Slavian. Generated by tools/i18n/extract.py; edit translations only.", *head, ""]
    for msgid, (plural, where) in messages.items():
        out.append(f"#: {where}")
        out.append(f'msgid "{escape(msgid)}"')
        have = (translations or {}).get(msgid, [])
        if plural is not None:
            out.append(f'msgid_plural "{escape(plural)}"')
            count = LANGUAGES[language]["plurals"] if language else 2
            for i in range(count):
                out.append(f'msgstr[{i}] "{escape(have[i]) if i < len(have) else ""}"')
        else:
            out.append(f'msgstr "{escape(have[0]) if have else ""}"')
        out.append("")
    return "\n".join(out)


def main():
    check = "--check" in sys.argv
    messages = collect()
    files = {OUT / "messages.pot": render(messages)}
    missing = {}
    for language in LANGUAGES:
        path = OUT / f"{language}.po"
        translations = parse_po(path)
        files[path] = render(messages, language, translations)
        missing[language] = [m for m in messages if not any(translations.get(m, []))]
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if check:
        problems = [f"{p.relative_to(ROOT)} is out of date" for p in stale]
        problems += [f"{lang}: {len(m)} strings untranslated, e.g. {m[0]!r}" for lang, m in missing.items() if m]
        for problem in problems:
            print(problem)
        sys.exit(1 if problems else 0)
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
    print(f"{len(messages)} strings; untranslated: " + ", ".join(f"{lang} {len(m)}" for lang, m in missing.items()))


if __name__ == "__main__":
    main()
